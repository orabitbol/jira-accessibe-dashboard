// t("key", { n: 3 }) — looks up the string for `lang` (falling back to
// English, then to the raw key itself so a missing translation is visible
// instead of silently blank), then does simple {placeholder} interpolation.
export function makeT(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  return function t(key, vars) {
    let s = dict[key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}
